# -*- coding: utf-8 -*-
from 时间换算 import 最少歇息
from 班表规则 import 白班要不要挪到下一天


def 查一个人(人名, 各组):
    问题 = []
    调整后 = []
    条序 = 0
    while 条序 < len(各组):
        原条 = 各组[条序]
        新条 = {
            "名字": 原条["名字"],
            "开始": 原条["开始"],
            "结束": 原条["结束"],
            "行": 原条["行"],
            "标记": 原条["标记"],
        }
        if 白班要不要挪到下一天(各组, 原条):
            新条["开始"] = 原条["开始"] + 24 * 60
            新条["结束"] = 原条["结束"] + 24 * 60
        调整后.append(新条)
        条序 = 条序 + 1
    调整后.sort(key=lambda 条: (条["开始"], 条["行"]))
    下标 = 0
    while 下标 < len(调整后) - 1:
        前 = 调整后[下标]
        后 = 调整后[下标 + 1]
        if 后["开始"] < 前["结束"]:
            问题.append((前["行"], 5, "两段班叠在一起", 人名, str(后["行"])))
        else:
            空隙 = 后["开始"] - 前["结束"]
            if 空隙 < 最少歇息:
                问题.append((前["行"], 6, "歇得不够", 人名, str(后["行"])))
        下标 = 下标 + 1
    return 问题
